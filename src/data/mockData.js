function makeChecklist(clientId, startDate, completedCount = 8) {
  const start = new Date(startDate)
  const due = new Date(start)
  due.setDate(due.getDate() + 7)
  const dueStr = due.toISOString().split('T')[0]
  const titles = [
    'Send welcome email', 'Request platform access', 'Schedule kickoff call',
    'Complete onboarding research form', 'Run social media audit', 'Run review analysis',
    'Set up member survey sequence', 'Deliver findings document',
  ]
  return titles.map((title, i) => ({
    id: `${clientId}-cl-${i}`,
    title,
    due: dueStr,
    completed: i < completedCount,
    completedAt: i < completedCount
      ? new Date(start.getTime() + (i + 1) * 86400000).toISOString().split('T')[0]
      : null,
    assignedTo: null,
  }))
}

